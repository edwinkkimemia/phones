export function getProduct(slug: string): ProductT | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function deals(): ProductT[] {
  return PRODUCTS.filter((p) => p.isDeal);
}

export function bestSellers(): ProductT[] {
  return [...PRODUCTS].sort((a, b) => b.soldCount - a.soldCount).slice(0, 8);
}

export function newArrivals(): ProductT[] {
  return PRODUCTS.filter((p) => p.isNew).concat(
    [...PRODUCTS].filter((p) => !p.isNew).slice(0, 4)
  ).slice(0, 8);
}
